#!/usr/bin/env node
/**
 * Build seed SQL for the postal_codes table from GeoNames.
 *
 *   node scripts/build-postal-codes.mjs GB US CA AU NZ IE
 *   node scripts/build-postal-codes.mjs --all
 *
 * Writes seed/postal_codes.sql, then:
 *   wrangler d1 execute gapfiller --local  --file=./seed/postal_codes.sql
 *   wrangler d1 execute gapfiller --remote --file=./seed/postal_codes.sql
 *
 * Source: https://download.geonames.org/export/zip/  (CC BY 4.0)
 * ATTRIBUTION IS REQUIRED — see migrations/0002_postal_codes.sql.
 *
 * Size warning: GB alone is ~1.7M rows and will not fit D1's per-database
 * limits comfortably alongside everything else. Seed only the countries you
 * actually sell in, and add more as you expand. --all is there for
 * completeness, not as a recommendation.
 */

import { mkdirSync, createWriteStream, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const BASE = 'https://download.geonames.org/export/zip';
const OUT_DIR = new URL('../seed/', import.meta.url).pathname;
const args = process.argv.slice(2);

if (args.length === 0) {
  console.error('Usage: node scripts/build-postal-codes.mjs GB US CA [...]  |  --all');
  process.exit(1);
}

const codes = args[0] === '--all' ? ['allCountries'] : args.map((a) => a.toUpperCase());

const sqlEscape = (s) => (s == null || s === '' ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const normalise = (s) => s.toUpperCase().replace(/[\s-]/g, '');

mkdirSync(OUT_DIR, { recursive: true });
const outPath = join(OUT_DIR, 'postal_codes.sql');
const out = createWriteStream(outPath);

out.write('-- Generated by scripts/build-postal-codes.mjs\n');
out.write('-- Source: GeoNames postal code data, CC BY 4.0\n');
out.write('-- Attribution to GeoNames is REQUIRED wherever this data is shown.\n');
out.write('BEGIN TRANSACTION;\n');

let total = 0;

for (const code of codes) {
  const work = join(tmpdir(), `geonames-${code}-${Date.now()}`);
  mkdirSync(work, { recursive: true });
  const zipPath = join(work, `${code}.zip`);

  process.stderr.write(`Fetching ${code}.zip ... `);
  const res = await fetch(`${BASE}/${code}.zip`);
  if (!res.ok) {
    process.stderr.write(`FAILED (${res.status}) — skipping\n`);
    rmSync(work, { recursive: true, force: true });
    continue;
  }
  const buf = Buffer.from(await res.arrayBuffer());
  const { writeFileSync, readFileSync } = await import('node:fs');
  writeFileSync(zipPath, buf);
  execFileSync('unzip', ['-o', '-q', zipPath, '-d', work]);

  const text = readFileSync(join(work, `${code}.txt`), 'utf8');
  let rows = 0;
  const values = [];

  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    // country, postal, place, admin1, admin1code, admin2, admin2code,
    // admin3, admin3code, lat, lng, accuracy
    const f = line.split('\t');
    const country = f[0];
    const postal = f[1] ? normalise(f[1]) : '';
    const lat = Number(f[9]);
    const lng = Number(f[10]);
    if (!country || !postal || !Number.isFinite(lat) || !Number.isFinite(lng)) continue;

    values.push(
      `(${sqlEscape(country)},${sqlEscape(postal)},${sqlEscape(f[2])},` +
      `${sqlEscape(f[3])},${lat.toFixed(5)},${lng.toFixed(5)},` +
      `${f[11] && Number.isFinite(Number(f[11])) ? Number(f[11]) : 'NULL'})`,
    );
    rows++;

    if (values.length >= 500) {
      out.write(
        `INSERT OR REPLACE INTO postal_codes ` +
        `(country_code,postal_code,place_name,admin_name1,lat,lng,accuracy) VALUES\n` +
        values.join(',\n') + ';\n',
      );
      values.length = 0;
    }
  }

  if (values.length) {
    out.write(
      `INSERT OR REPLACE INTO postal_codes ` +
      `(country_code,postal_code,place_name,admin_name1,lat,lng,accuracy) VALUES\n` +
      values.join(',\n') + ';\n',
    );
  }

  rmSync(work, { recursive: true, force: true });
  total += rows;
  process.stderr.write(`${rows.toLocaleString()} rows\n`);
}

out.write('COMMIT;\n');
out.end();

process.stderr.write(`\nWrote ${total.toLocaleString()} rows to ${outPath}\n`);
process.stderr.write('Load with: wrangler d1 execute gapfiller --remote --file=./seed/postal_codes.sql\n');
