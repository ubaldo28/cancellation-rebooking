/**
 * One band of the working week, in minutes from midnight in the operator's own
 * timezone — 540 is 09:00. Render them through `operator.timezone` and not the
 * reader's clock: a business open until 18:00 in Los Angeles is not open until
 * 02:00, which is what the browser would make of these numbers.
 *
 * A weekday can have several bands (a lunch break is two), and a weekday that
 * appears in no band is a day this business does not work. An operator who has
 * never set hours has none at all, so an empty array means "they have not
 * said" and must not be drawn as a week of closed days.
 */
export interface PublicHours {
  /** 0 = Sunday. */
  weekday: number;
  start_minute: number;
  end_minute: number;
}

