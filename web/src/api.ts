/**
 * Worker API client.
 *
 * Auth is a session cookie set by the Worker, so every request sends
 * credentials. The browser stays on one origin in both environments, which is
 * what keeps that cookie first-party: in development Vite proxies /api to
 * wrangler dev, and in production the same Worker serves both this bundle and
 * the API. So VITE_API_URL is set in no build today and BASE is the empty
 * string, making every path below same-origin and CORS irrelevant to the app's
 * own requests. It stays available for pointing a local front end at a
 * deployed Worker; that origin then has to appear in ALLOWED_ORIGINS.
 */

import { formatMoney } from './lib/format';

const BASE = (import.meta.env.VITE_API_URL ?? '').replace(/\/$/, '');

export class ApiError extends Error {
  constructor(public status: number, message: string, public code?: string) {
    super(message);
  }
}

async function request<T>(path: string, init: RequestInit = {}): Promise<T> {
  const res = await fetch(`${BASE}${path}`, {
    ...init,
    credentials: 'include',
    headers: {
      // A FormData body has to set its own content-type: the boundary is
      // generated by the browser and a hand-written header loses it.
      ...(init.body && !(init.body instanceof FormData)
        ? { 'content-type': 'application/json' } : {}),
      ...init.headers,
    },
  });

  if (res.status === 204) return undefined as T;

  let body: any = null;
  try { body = await res.json(); } catch { /* empty or non-JSON */ }

  if (!res.ok) {
    throw new ApiError(res.status, body?.error ?? `Request failed (${res.status})`, body?.code);
  }
  return body as T;
}

const get = <T>(p: string) => request<T>(p);
const post = <T>(p: string, body?: unknown) =>
  request<T>(p, { method: 'POST', body: body === undefined ? undefined : JSON.stringify(body) });
const patch = <T>(p: string, body: unknown) =>
  request<T>(p, { method: 'PATCH', body: JSON.stringify(body) });
const put = <T>(p: string, body: unknown) =>
  request<T>(p, { method: 'PUT', body: JSON.stringify(body) });
const del = <T>(p: string) => request<T>(p, { method: 'DELETE' });

